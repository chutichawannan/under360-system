const swap = (txt, file, pairs) => {
  for (const [o, n] of pairs) {
    if (txt.includes(n)) continue;
    const c = txt.split(o).length - 1;
    must(c === 1, file + ': หาข้อความเดิมเจอ ' + c + ' ครั้ง (ต้องเจอ 1) — หยุด ไม่เดา\n   "' + o.slice(0, 70) + '…"');
    txt = txt.split(o).join(n);
  }
  return txt;
};

