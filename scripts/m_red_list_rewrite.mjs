const lines = fs.readFileSync(F, 'utf8').split('\n');
const s = lines.findIndex(l => l.trim() === '## ห้อง M');
must(s >= 0, 'ไม่เจอหัวข้อ "## ห้อง M" — หยุด ไม่เดา');
let e = lines.length;
for (let i = s + 1; i < lines.length; i++) if (lines[i].startsWith('## ')) { e = i; break; }

const cut = lines.slice(s, e);
must(cut.filter(l => l.startsWith('## ')).length === 1, 'ช่วงที่จะแทนมีหัวข้อเกิน 1 อัน — หยุด');
must(!/ห้อง (05|u|pm|cc|k|เจ|นิว|buyer|06)/.test(cut.slice(1).join('\n')), 'ช่วงที่จะแทนมีของห้องอื่นปน — หยุด');

if (cut.join('\n').trim() === NEW.trim()) { console.log('⏭️  section ห้อง m เขียนใหม่ไว้แล้ว'); process.exit(0); }

const before = lines.length;
lines.splice(s, e - s, ...NEW.split('\n'));
fs.writeFileSync(F, lines.join('\n'));

const after = fs.readFileSync(F, 'utf8');
must((after.match(/^## /gm) || []).length === 15, 'จำนวนหัวข้อห้องเปลี่ยนไป — ผิดแน่');
console.log('✅ เขียน section ห้อง M ใหม่: ' + (e - s) + ' → ' + NEW.split('\n').length + ' บรรทัด (ไฟล์ ' + before + ' → ' + lines.length + ')');
