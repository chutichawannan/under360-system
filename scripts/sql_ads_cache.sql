-- 🔒 RLS ปิดสนิท ไม่มี policy ให้ anon เลย — ตั้งใจ
--    ตัวเลขค่าโฆษณาอยู่หลังด่านรหัสของหน้า /ads · กุญแจ anon ฝังอยู่ในทุกหน้าเว็บ
--    ถ้าเปิดให้ anon อ่านได้ = เอาของหลังด่านมาวางหน้าด่าน · ฝั่ง server อ่านด้วยกุญแจ service role ซึ่งข้าม RLS อยู่แล้ว
--
-- ⚠️ ต้องทำ 2 อย่างถึงจะมีผล (ทำอย่างเดียวไม่พอ):
--    ① รันไฟล์นี้ใน Supabase SQL Editor
--    ② ใส่ env `SUPABASE_SERVICE_ROLE` ในโปรเจค Vercel ของเว็บ (under360-web)
--    ไม่ทำ = ไม่พัง หน้ายังทำงานปกติทุกอย่าง แค่เครื่องเย็นจะช้าเหมือนเดิม

create table if not exists ads_cache (
  key        text primary key,          -- ช่วงวันที่ขอ เช่น '2026-09-08|2026-09-15'
  payload    jsonb not null,            -- ก้อนตัวเลขที่คำนวณเสร็จแล้ว
  fetched_at timestamptz not null default now()
);

alter table ads_cache enable row level security;
-- ไม่สร้าง policy ใดๆ = anon อ่าน/เขียนไม่ได้เลย (service role ข้าม RLS ได้ตามปกติ)
