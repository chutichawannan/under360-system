const resolve = (list, q) => {
  const exact = list.find((x) => x.n === q);
  if (exact) return exact;
  const best = list.map((x) => ({ x, s: similar(q, x.n) })).sort((a, b) => b.s - a.s)[0];
  return best && best.s >= MIN ? best.x : null;
};

